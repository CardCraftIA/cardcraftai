-- CardCraft Catalog Core
-- Canonical, provenance-aware internal catalog. Applied first to CardCraftAI-TEST.
-- Runtime reads our database; external sources are synchronization inputs, not the product source of truth.

create extension if not exists pg_trgm;

create table if not exists public.catalog_games (
  slug text primary key,
  name text not null,
  publisher text not null default '',
  active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint catalog_games_slug_format check (slug ~ '^[a-z0-9][a-z0-9-]{1,39}$')
);

create table if not exists public.catalog_sources (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  homepage text not null default '',
  source_type text not null,
  license_name text not null default '',
  license_url text not null default '',
  redistribution_mode text not null default 'review',
  attribution_text text not null default '',
  active boolean not null default true,
  terms_verified_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint catalog_sources_code_format check (code ~ '^[a-z0-9][a-z0-9_-]{1,39}$'),
  constraint catalog_sources_type_check check (source_type in ('repository','api','official','community','manual')),
  constraint catalog_sources_redistribution_check check (redistribution_mode in ('mirror_allowed','metadata_allowed','reference_only','review'))
);

create table if not exists public.catalog_sets (
  id uuid primary key default gen_random_uuid(),
  game_slug text not null references public.catalog_games(slug) on delete restrict,
  canonical_key text not null unique,
  code text not null default '',
  name text not null,
  name_search text not null,
  series text not null default '',
  release_date date,
  printed_total integer,
  total integer,
  region text not null default '',
  status text not null default 'active',
  source_count integer not null default 0,
  attributes jsonb not null default '{}'::jsonb,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint catalog_sets_status_check check (status in ('active','unverified','retired'))
);

create table if not exists public.catalog_cards (
  id uuid primary key default gen_random_uuid(),
  game_slug text not null references public.catalog_games(slug) on delete restrict,
  set_id uuid references public.catalog_sets(id) on delete set null,
  canonical_key text not null unique,
  collector_number text not null default '',
  local_id text not null default '',
  category text not null default '',
  rarity text not null default '',
  illustrator text not null default '',
  hp integer,
  dex_ids integer[] not null default '{}',
  release_date date,
  status text not null default 'active',
  verification_status text not null default 'source_verified',
  data_quality smallint not null default 50,
  source_count integer not null default 0,
  attributes jsonb not null default '{}'::jsonb,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint catalog_cards_status_check check (status in ('active','unverified','retired')),
  constraint catalog_cards_verification_check check (verification_status in ('source_verified','multi_source','community_verified','pending_review')),
  constraint catalog_cards_quality_check check (data_quality between 0 and 100)
);

create table if not exists public.catalog_card_localizations (
  id uuid primary key default gen_random_uuid(),
  card_id uuid not null references public.catalog_cards(id) on delete cascade,
  language text not null,
  name text not null,
  name_search text not null,
  description text not null default '',
  rules jsonb not null default '{}'::jsonb,
  image_url text not null default '',
  image_small_url text not null default '',
  image_status text not null default 'remote_reference',
  source_count integer not null default 0,
  attributes jsonb not null default '{}'::jsonb,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(card_id, language),
  constraint catalog_card_localizations_language_check check (language ~ '^[a-z]{2,3}(-[a-z0-9]{2,8})?$'),
  constraint catalog_card_localizations_image_status_check check (image_status in ('remote_reference','local_cached','unavailable','rights_review'))
);

create table if not exists public.catalog_card_variants (
  id uuid primary key default gen_random_uuid(),
  card_id uuid not null references public.catalog_cards(id) on delete cascade,
  variant_key text not null,
  variant_type text not null default 'normal',
  subtype text not null default '',
  size text not null default 'standard',
  stamps text[] not null default '{}',
  external_ids jsonb not null default '{}'::jsonb,
  attributes jsonb not null default '{}'::jsonb,
  verification_status text not null default 'source_verified',
  source_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(card_id, variant_key),
  constraint catalog_card_variants_verification_check check (verification_status in ('source_verified','multi_source','community_verified','pending_review'))
);

create table if not exists public.catalog_aliases (
  id bigint generated by default as identity primary key,
  card_id uuid not null references public.catalog_cards(id) on delete cascade,
  language text not null default 'und',
  alias text not null,
  alias_search text not null,
  alias_type text not null default 'name',
  source_id bigint references public.catalog_sources(id) on delete set null,
  created_at timestamptz not null default now(),
  unique(card_id, language, alias_search, alias_type)
);

create table if not exists public.catalog_source_records (
  id uuid primary key default gen_random_uuid(),
  source_id bigint not null references public.catalog_sources(id) on delete cascade,
  source_key text not null,
  language text not null default 'und',
  entity_type text not null default 'card',
  payload_hash text not null,
  payload jsonb not null default '{}'::jsonb,
  source_updated_at timestamptz,
  fetched_at timestamptz not null default now(),
  unique(source_id, source_key, language, entity_type),
  constraint catalog_source_records_entity_check check (entity_type in ('game','set','card','variant','price_reference'))
);

create table if not exists public.catalog_source_links (
  id bigint generated by default as identity primary key,
  source_id bigint not null references public.catalog_sources(id) on delete cascade,
  source_key text not null,
  language text not null default 'und',
  card_id uuid references public.catalog_cards(id) on delete cascade,
  set_id uuid references public.catalog_sets(id) on delete cascade,
  variant_id uuid references public.catalog_card_variants(id) on delete cascade,
  confidence smallint not null default 100,
  field_coverage jsonb not null default '{}'::jsonb,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  unique(source_id, source_key, language, card_id, set_id, variant_id),
  constraint catalog_source_links_confidence_check check (confidence between 0 and 100),
  constraint catalog_source_links_target_check check (card_id is not null or set_id is not null or variant_id is not null)
);

create table if not exists public.catalog_sync_runs (
  id uuid primary key default gen_random_uuid(),
  source_id bigint not null references public.catalog_sources(id) on delete restrict,
  mode text not null default 'incremental',
  status text not null default 'running',
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  discovered_count integer not null default 0,
  inserted_count integer not null default 0,
  updated_count integer not null default 0,
  conflict_count integer not null default 0,
  error_count integer not null default 0,
  source_revision text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  constraint catalog_sync_runs_mode_check check (mode in ('inventory','hydrate','incremental','full_rebuild','manual')),
  constraint catalog_sync_runs_status_check check (status in ('running','completed','partial','failed'))
);

create table if not exists public.catalog_conflicts (
  id uuid primary key default gen_random_uuid(),
  card_id uuid references public.catalog_cards(id) on delete cascade,
  field_name text not null,
  current_value jsonb,
  candidate_value jsonb,
  current_source_id bigint references public.catalog_sources(id) on delete set null,
  candidate_source_id bigint references public.catalog_sources(id) on delete set null,
  status text not null default 'open',
  resolution_note text not null default '',
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  constraint catalog_conflicts_status_check check (status in ('open','accepted_candidate','kept_current','merged','dismissed'))
);

create table if not exists public.catalog_discovery_submissions (
  id uuid primary key default gen_random_uuid(),
  submitted_by uuid not null references auth.users(id) on delete cascade,
  game_slug text not null references public.catalog_games(slug) on delete restrict,
  claimed_name text not null,
  claimed_set text not null default '',
  claimed_number text not null default '',
  claimed_language text not null default '',
  claimed_variant text not null default '',
  evidence_notes text not null default '',
  evidence_urls text[] not null default '{}',
  status text not null default 'pending',
  matched_card_id uuid references public.catalog_cards(id) on delete set null,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  review_note text not null default '',
  constraint catalog_discovery_status_check check (status in ('pending','needs_evidence','accepted','duplicate','rejected')),
  constraint catalog_discovery_notes_length check (char_length(evidence_notes) <= 4000)
);

