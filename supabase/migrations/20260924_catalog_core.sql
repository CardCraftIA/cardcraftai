create or replace function public.search_catalog_core(
  p_query text,
  p_game_slug text default null,
  p_language text default null,
  p_limit integer default 40
)
returns table (
  card_id uuid, game_slug text, set_id uuid, set_code text, set_name text,
  collector_number text, rarity text, illustrator text, language text,
  card_name text, image_url text, image_small_url text,
  verification_status text, source_count integer, rank_score real
)
language sql
stable
security invoker
set search_path = public
as $$
  with q as (select lower(btrim(coalesce(p_query,''))) as value),
  ranked as (
    select c.id as card_id,c.game_slug,c.set_id,coalesce(s.code,'') as set_code,
      coalesce(s.name,'') as set_name,c.collector_number,c.rarity,c.illustrator,
      l.language,l.name as card_name,l.image_url,l.image_small_url,
      c.verification_status,c.source_count,
      greatest(
        case when lower(l.name_search)=q.value then 1.0
             when lower(l.name_search) like q.value||'%' then 0.95
             when lower(l.name_search) like '%'||q.value||'%' then 0.85
             else similarity(lower(l.name_search),q.value) end,
        similarity(lower(coalesce(s.name_search,'')),q.value),
        similarity(lower(coalesce(c.collector_number,'')),q.value)
      )::real as rank_score
    from public.catalog_cards c
    join public.catalog_card_localizations l on l.card_id=c.id
    left join public.catalog_sets s on s.id=c.set_id
    cross join q
    where c.status in ('active','unverified')
      and (p_game_slug is null or c.game_slug=p_game_slug)
      and (p_language is null or l.language=p_language)
      and (
        lower(l.name_search) % q.value
        or lower(l.name_search) like '%'||q.value||'%'
        or lower(coalesce(s.name_search,'')) % q.value
        or lower(coalesce(c.collector_number,'')) like '%'||q.value||'%'
      )
  )
  select * from ranked
  where rank_score >= 0.18
  order by rank_score desc,card_name,set_name,collector_number
  limit greatest(1,least(coalesce(p_limit,40),100));
$$;

revoke all on function public.search_catalog_core(text,text,text,integer) from public, anon;
grant execute on function public.search_catalog_core(text,text,text,integer) to authenticated;
